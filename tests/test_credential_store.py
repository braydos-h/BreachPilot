def test_add_forces_confirmed_false_even_when_caller_supplies_true(
    monkeypatch,
    tmp_path,
    caplog,
):
    """Bypass 1 (validated-gate forge): ``add`` must not persist a caller-supplied
    ``confirmed=True``. Without this, a harvest path (or a hand-built record) could
    store a confirmed credential that reloads HMAC-verified -- silently bypassing
    the ``confirm_credential(validated=True)`` gate the exploit loop trusts before
    reusing a credential at full access. The *only* path to confirmed=True stays
    ``confirm_credential``; ``add`` is the harvester and must yield unconfirmed."""
    import logging

    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    store = CredentialStore(tmp_path)
    rec = _rec(username="admin", target_host="10.0.0.50", confirmed=True)
    with caplog.at_level(logging.WARNING, logger="tools.credential_store"):
        store.add(rec)
    # the record object itself is forced back to unconfirmed before it is stored
    assert rec.confirmed is False
    assert store.all_credentials()[0].confirmed is False
    # on-disk: confirmed=False, so the HMAC we just wrote covers False (not True)
    line = json.loads((tmp_path / "credentials.jsonl").read_text(encoding="utf-8").strip().splitlines()[-1])
    assert line["confirmed"] is False
    assert "sig" in line and line["sig"]
    # reload: verified signature + confirmed=False -> stays False (no promotion
    # from a forge; only confirm_credential(validated=True) can flip this)
    store2 = CredentialStore(tmp_path)
    assert store2.all_credentials()[0].confirmed is False
    # the forge attempt was not silent -- the operator-visible warning fired
    assert any("forcing False" in r.message for r in caplog.records)


