def test_store_writes_ciphertext_disk_memory_plaintext(monkeypatch, tmp_path):
    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    store = CredentialStore(tmp_path)
    assert store.encryption_enabled is True
    store.add(_rec(password=_CLEARTEXT))

