"""Regression tests for the encrypted credential store (Tier 0 item 0.3, Phase B).

Covers:
1. ``_Vault`` -- Fernet at-rest encryption, env-key vs 0600-keyfile resolution,
   loud plaintext fallback when ``cryptography`` is absent, fail-open decrypt for
   legacy/wrong-key reads.
2. ``CredentialStore`` -- in-memory plaintext / on-disk ciphertext round-trip,
   ``confirm_credential`` as the *only* path to ``confirmed=True``, dedup, and
   legacy plaintext files still loading.
3. The ``cred_store_add/get/list/confirm`` MCP tools end-to-end -- the on-disk
   vault holds ciphertext, the audit log never holds the cleartext secret, and
   ``confirmed`` only flips via the deliberate confirm call.
"""

