import time
from pathlib import Path
from typing import Any

import pytest
from cryptography.fernet import Fernet

from tools.credential_store import CredentialRecord, CredentialStore, _Vault

_CLEARTEXT = "super-secret-password-42!"
_NTLM = "aad3b435b51404eeaad3b435b51404ee"


def _rec(
    username: str = "admin",
    password: str = _CLEARTEXT,
    ctype: str = "password",
    target_host: str = "10.0.0.50",
    confirmed: bool = False,
) -> CredentialRecord:
    return CredentialRecord(
        timestamp=time.time(),
        source_host="10.0.0.50",
        target_host=target_host,
        username=username,
        password=password,
        credential_type=ctype,
        source_action="test",
        confirmed=confirmed,
    )


# ── 1. _Vault ───────────────────────────────────────────────────────────────


def test_vault_env_key_roundtrip(monkeypatch, tmp_path):
    key = Fernet.generate_key().decode()
    monkeypatch.setenv("AI_NMAP_VAULT_KEY", key)
    v = _Vault(tmp_path)
    assert v.enabled is True
    token = v.encrypt(_CLEARTEXT)
    assert token != _CLEARTEXT
    assert token.startswith("gAAAAA")  # Fernet token prefix
    assert v.decrypt(token) == _CLEARTEXT


def test_vault_keyfile_autogenerated(monkeypatch, tmp_path):
    """The keyfile is auto-generated OUTSIDE the workspace tree (0600), so the
    AI's unrestricted workspace reads can never reach it."""
    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    vault_dir = tmp_path / "vault_home"
    monkeypatch.setenv("BREACHPILOT_VAULT_DIR", str(vault_dir))
    store_dir = tmp_path / "workspace"
    v = _Vault(store_dir)
    assert v.enabled is True
    assert (store_dir / ".vault_key").exists() is False  # never in-workspace
    assert v._keyfile.parent == vault_dir
    assert v._keyfile.exists()
    import os as _os

    assert oct(v._keyfile.stat().st_mode & 0o777) == "0o600"
    token = v.encrypt(_CLEARTEXT)
    assert v.decrypt(token) == _CLEARTEXT


def test_vault_key_is_private_before_first_write(monkeypatch, tmp_path):
    """The key is created with private mode before key bytes are written."""
    import os

    monkeypatch.delenv("AI_NMAP_VAULT_KEY", raising=False)
    vault_dir = tmp_path.parent / f"{tmp_path.name}-vault"
    monkeypatch.setenv("BREACHPILOT_VAULT_DIR", str(vault_dir))
    original_write = os.write
    observed_modes: list[int] = []

    def inspect_before_write(fd: int, data: bytes) -> int:
        observed_modes.append(os.fstat(fd).st_mode & 0o777)
        return original_write(fd, data)

    monkeypatch.setattr(os, "write", inspect_before_write)
    vault = _Vault(tmp_path / "workspace")
    assert vault.enabled
    assert observed_modes and all(mode == 0o600 for mode in observed_modes)


